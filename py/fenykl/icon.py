"""Generator of the settings tab's icon (sdk/lib/ui_icon_em10ii.h): the committed index grid,
bright and dim, encoded as the GUI's 8-bpp run-length images. Run `python3 -m fenykl.icon` after
changing the grid; a test checks that the committed header is up to date."""

from pathlib import Path

from .assets import AssetError, Bitmap, encode_bitmap8
from .sdk import SDK

GRID = SDK / "lib" / "ui_icon_em10ii.txt"
HEADER = SDK / "lib" / "ui_icon_em10ii.h"
WIDTH, HEIGHT = 38, 40
# The dim icon (the tab column's unselected tabs): the bulb and the green parts in the stock dim
# icons' greys, the plate kept.
DIM = {7: 71, 8: 70, 67: 71, 46: 70}


def read_grid(path: Path = GRID) -> Bitmap:
    """The bright icon: `path`'s rows of decimal indices, `#` lines skipped."""
    rows = [
        [int(v) for v in line.split()]
        for line in path.read_text().splitlines()
        if line.strip() and not line.startswith("#")
    ]
    if len(rows) != HEIGHT or any(len(r) != WIDTH for r in rows):
        raise AssetError(f"{path}: not {WIDTH} x {HEIGHT} indices")
    return Bitmap(WIDTH, HEIGHT, 0x03, bytes(v for r in rows for v in r))


def dim(bright: Bitmap) -> Bitmap:
    return Bitmap(
        bright.width,
        bright.height,
        bright.fmt,
        bytes(DIM.get(v, v) for v in bright.pixels),
    )


def _table(name: str, bitmap: Bitmap) -> str:
    data, size = encode_bitmap8(bitmap.width, bitmap.height, bitmap.pixels)
    words = [int.from_bytes(data[i : i + 4], "little") for i in range(0, len(data), 4)]
    lines = [
        "\t" + ", ".join(f"0x{w:08X}u" for w in words[i : i + 6]) + ","
        for i in range(0, len(words), 6)
    ]
    return (
        f"#define FUI_ICON_{name.upper()}_SIZE {size}u\n"
        f"static const uint32_t fui_icon_{name}[{len(words)}] = {{\n"
        + "\n".join(lines)
        + "\n};\n"
    )


def header(bright: Bitmap) -> str:
    """ui_icon_em10ii.h for the bright icon `bright` and its dim version."""
    return (
        "/* Generated by python3 -m fenykl.icon from ui_icon_em10ii.txt: do not edit. The settings\n"
        "   tab's icon, bright and dim, as fmt 0x03 images (header word, six 10-bit codes per u64)\n"
        "   and the sizes their image records give. */\n"
        f"#define FUI_ICON_W {bright.width}u\n"
        f"#define FUI_ICON_H {bright.height}u\n"
        + _table("bright", bright)
        + _table("dim", dim(bright))
    )


def main() -> None:
    HEADER.write_text(header(read_grid()))


if __name__ == "__main__":
    main()
