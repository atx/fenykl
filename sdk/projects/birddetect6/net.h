/*
 * The bird detector network wide-k326-pot (fenykl-nn integer spec: 3x3 convs with zero padding 1,
 * int32 accumulators; the int8 stem (acc + round) >> shift, the power-of-two layers (weights 0,
 * +-1, +-2, +-4) (acc * m + round) >> shift with a u8 multiplier m per output channel (one udf00),
 * both clamped to u8; a raw int32 head of two channels, heat map and presence) as
 * generated code. Pure code, no firmware calls: runs on CPU1 and in the GDB simulator
 * (tests/sim/birddetect6).
 *
 * Input: the IPU's 96x72 YUYV frame, copied into a padded buffer (a zero row above and below, a
 * zero pixel pair on the left). The stem (generated int8 code, bd6_gen.S) reads it in place: its
 * output x reads Y columns 2x-1..2x+1 and chroma samples x-1 and x, all 4 bytes apart per output
 * pixel, so the 2x chroma upsampling of the spec folds into the weights.
 *
 * Power-of-two layers read pair words (pixel p in the low 16 bits, pixel p + 1 in the high 16
 * bits) of padded CHW planes through generated code (bd6_gen.S), the weights compiled in, split
 * into blocks of output channels that fit the I-cache: all calls of a block, then the next block.
 * Per output channel the code adds the +-4 taps, doubles both lanes, adds the +-2 taps, doubles,
 * adds the +-1 taps (Horner by magnitude): the lanes start at 0x2000 (0x4000 or 0x8000 when the
 * largest groups are empty) and end at 0x8000 + sum, the bias is in the epilogue. Pools write pair words, the power-of-two layers before another power-of-two layer too
 * (each output byte stored into both of its words); borders are zeroed once by bd6_net_init and
 * never written again.
 */
#ifndef BD6_NET_H
#define BD6_NET_H

#include <stdbool.h>
#include <stdint.h>

#define BD6_IN_W 96u
#define BD6_IN_H 72u
#define BD6_FRAME_PITCH (2u * BD6_IN_W)		/* YUYV bytes per row */
#define BD6_FRAME_BYTES (BD6_FRAME_PITCH * BD6_IN_H)
#define BD6_PIN_PITCH (BD6_FRAME_PITCH + 4u)	/* padded rows; gen_model.py bakes it in */
#define BD6_PIN_H (BD6_IN_H + 2u)

#define BD6_L0_C 12u		/* stem output, CHW unpadded */
#define BD6_L0_H 36u
#define BD6_L0_W 48u
#define BD6_L2_C 16u		/* L1 pool and L2 */
#define BD6_L2_H 18u
#define BD6_L2_W 24u
#define BD6_P1_W (BD6_L2_W + 2u)	/* L2's padded input planes */
#define BD6_P1_H (BD6_L2_H + 2u)
#define BD6_GRID_W 12u		/* L3 pool .. L10 */
#define BD6_GRID_H 9u
#define BD6_CELLS (BD6_GRID_W * BD6_GRID_H)
#define BD6_TRUNK_C 32u
#define BD6_P3_W (BD6_GRID_W + 2u)	/* L4..L9 padded input planes */
#define BD6_P3_H (BD6_GRID_H + 2u)
#define BD6_P3_PLANE (BD6_P3_W * BD6_P3_H)
#define BD6_TRUNK 6u		/* L4..L9 */
#define BD6_HEAD_C 2u		/* head channels: heat map, presence */
#define BD6_LOGITS (BD6_HEAD_C * BD6_CELLS)

/* A generated function: in, out at the first of its output pixels. */
typedef void bd6_gen_fn(const void *in, void *out);

/* A power-of-two 3x3 layer (bd6_model.c, bd6_gen.S): per block of output channels a function
   computing 4 neighbouring output pixels of each of its channels. */
struct bd6_pot {
	unsigned int nblk;
	bd6_gen_fn *const *blk;
};

/* bd6_model.c and bd6_gen.S, generated by gen_model.py. */
extern const char bd6_model_name[], bd6_model_commit[];
extern const int32_t bd6_threshold;		/* a frame fires if its presence sum >= */
#define BD6_CENTROID_N 16u
extern const uint8_t bd6_centroid_table[BD6_CENTROID_N];	/* point weight per (peak - logit) >> k */
extern const uint8_t bd6_centroid_k;
extern const struct bd6_pot bd6_l2, bd6_trunk[BD6_TRUNK];
extern const uint32_t bd6_selftest_sum[];	/* bd6_logit_sum per enum bd6_pattern */
/* BD6_GEN_PX output pixels per call: stem from the padded input (all channels, CHW), head from L9
   (both channels, int32). gen_model.py PX. */
#define BD6_GEN_PX 2u
bd6_gen_fn bd6_stem, bd6_head;

/* Stages, timed one by one; the pause callback gets the stage of the band just finished. */
enum bd6_stage {
	BD6_ST_INPUT,
	BD6_ST_L0,
	BD6_ST_L1,
	BD6_ST_L2,
	BD6_ST_L3,
	BD6_ST_L4,	/* .. L9 */
	BD6_ST_L10 = BD6_ST_L4 + BD6_TRUNK,
	BD6_STAGES,
};

/* Inputs of the fenykl-nn test vectors, for the self-test (gen_model.py SELFTEST order). */
enum bd6_pattern {
	BD6_PAT_HGRAD,
	BD6_PAT_VGRAD,
	BD6_PAT_CHECKER,
	BD6_PAT_HGRAD_NEUTRAL,	/* Y hgradient, U = V = 128 */
	BD6_PAT_U0_V255,	/* Y 128 */
	BD6_PATTERNS,
};

struct bd6_net {
	uint8_t in[BD6_PIN_H * BD6_PIN_PITCH];
	uint8_t l0[BD6_L0_C * BD6_L0_H * BD6_L0_W];
	uint32_t p1[BD6_L0_C * BD6_P1_H * BD6_P1_W];	/* L1 */
	uint8_t l2[BD6_L2_C * BD6_L2_H * BD6_L2_W];
	uint32_t pa[BD6_TRUNK_C * BD6_P3_PLANE];	/* L3, L5, L7 */
	uint32_t pb[BD6_TRUNK_C * BD6_P3_PLANE];	/* L4, L6, L8 */
	uint8_t l9[BD6_TRUNK_C * BD6_CELLS];
	uint32_t row[BD6_L2_W / 4];			/* one u8 row */
	int32_t logit[BD6_LOGITS];	/* [channel][9][12]: heat map, presence */
} __attribute__((aligned(64)));

/* end: the stage's last band. */
typedef void bd6_pause_fn(void *ctx, enum bd6_stage st, bool end);

/* Clears all buffers (the zero borders). */
void bd6_net_init(struct bd6_net *n);
/* Copies a 96x72 YUYV frame (word aligned, pitch BD6_FRAME_PITCH) into the input. */
void bd6_net_input(struct bd6_net *n, const uint8_t *frame);
/* The input of a test pattern. */
void bd6_net_pattern(struct bd6_net *n, enum bd6_pattern p);
/* Runs L0..L10 on n->in; pause (if not NULL) after each band: a stem row, an output row of a block
   of a power-of-two layer, a whole pool or the head (at most ~0.2 M cycles apart). */
void bd6_net_run(struct bd6_net *n, bd6_pause_fn *pause, void *ctx);
/* Rotate-add checksum of both logit channels in raster order. */
uint32_t bd6_logit_sum(const int32_t *logit);

#endif
