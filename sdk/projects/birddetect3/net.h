/*
 * The bird detector network wide-k285 (fenykl-nn integer spec: 3x3 convs with zero padding 1, int32
 * accumulators, hidden layers (acc + round) >> shift clamped to u8, raw int32 head) on nnbench's
 * kernels. Pure code, no firmware calls: runs on CPU1 and in the GDB simulator
 * (tests/sim/birddetect3).
 *
 * Input: the IPU's 96x72 YUYV frame, copied into a padded buffer (a zero row above and below, a
 * zero pixel pair on the left). The stem (generated int8 code, bd3_gen.S) reads it in place: its
 * output x reads Y columns 2x-1..2x+1 and chroma samples x-1 and x, all 4 bytes apart per output
 * pixel, so the 2x chroma upsampling of the spec folds into the weights.
 *
 * Ternary layers read pair words (pixel p in the low 16 bits, pixel p + 1 in the high 16 bits) of
 * padded CHW planes through generated code (bd3_gen.S), the weights compiled in, split into blocks
 * of output channels that fit the I-cache: all calls of a block, then the next block. Pools write
 * pair words, the ternary layers before another ternary layer too (each output byte stored into both
 * of its words); borders are zeroed once by bd3_net_init and never written again.
 */
#ifndef BD3_NET_H
#define BD3_NET_H

#include <stdbool.h>
#include <stdint.h>

#define BD3_IN_W 96u
#define BD3_IN_H 72u
#define BD3_FRAME_PITCH (2u * BD3_IN_W)		/* YUYV bytes per row */
#define BD3_FRAME_BYTES (BD3_FRAME_PITCH * BD3_IN_H)
#define BD3_PIN_PITCH (BD3_FRAME_PITCH + 4u)	/* padded rows; gen_model.py bakes it in */
#define BD3_PIN_H (BD3_IN_H + 2u)

#define BD3_L0_C 12u		/* stem output, CHW unpadded */
#define BD3_L0_H 36u
#define BD3_L0_W 48u
#define BD3_L2_C 16u		/* L1 pool and L2 */
#define BD3_L2_H 18u
#define BD3_L2_W 24u
#define BD3_P1_W (BD3_L2_W + 2u)	/* L2's padded input planes */
#define BD3_P1_H (BD3_L2_H + 2u)
#define BD3_GRID_W 12u		/* L3 pool .. L9 */
#define BD3_GRID_H 9u
#define BD3_CELLS (BD3_GRID_W * BD3_GRID_H)
#define BD3_TRUNK_C 28u
#define BD3_P3_W (BD3_GRID_W + 2u)	/* L4..L8 padded input planes */
#define BD3_P3_H (BD3_GRID_H + 2u)
#define BD3_P3_PLANE (BD3_P3_W * BD3_P3_H)
#define BD3_TRUNK 5u		/* L4..L8 */

/* A generated function: in, out at the first of its output pixels. */
typedef void bd3_gen_fn(const void *in, void *out);

/* A ternary 3x3 layer (bd3_model.c, bd3_gen.S): per block of output channels a function computing
   4 neighbouring output pixels of each of its channels. */
struct bd3_tern {
	unsigned int nblk;
	bd3_gen_fn *const *blk;
};

/* bd3_model.c and bd3_gen.S, generated by gen_model.py. */
extern const char bd3_model_name[], bd3_model_commit[];
extern const int32_t bd3_threshold;		/* a frame fires if its top logit >= */
#define BD3_CENTROID_N 16u
extern const uint8_t bd3_centroid_table[BD3_CENTROID_N];	/* point weight per (peak - logit) >> k */
extern const uint8_t bd3_centroid_k;
extern const struct bd3_tern bd3_l2, bd3_trunk[BD3_TRUNK];
extern const uint32_t bd3_selftest_sum[];	/* bd3_logit_sum per enum bd3_pattern */
/* BD3_GEN_PX output pixels per call: stem from the padded input (all channels, CHW), head from L8
   (int32). gen_model.py PX. */
#define BD3_GEN_PX 2u
bd3_gen_fn bd3_stem, bd3_head;

/* Stages, timed one by one; the pause callback gets the stage of the band just finished. */
enum bd3_stage {
	BD3_ST_INPUT,
	BD3_ST_L0,
	BD3_ST_L1,
	BD3_ST_L2,
	BD3_ST_L3,
	BD3_ST_L4,	/* .. L8 */
	BD3_ST_L9 = BD3_ST_L4 + BD3_TRUNK,
	BD3_STAGES,
};

/* Inputs of the fenykl-nn test vectors, for the self-test (gen_model.py SELFTEST order). */
enum bd3_pattern {
	BD3_PAT_HGRAD,
	BD3_PAT_VGRAD,
	BD3_PAT_CHECKER,
	BD3_PAT_HGRAD_NEUTRAL,	/* Y hgradient, U = V = 128 */
	BD3_PAT_U0_V255,	/* Y 128 */
	BD3_PATTERNS,
};

struct bd3_net {
	uint8_t in[BD3_PIN_H * BD3_PIN_PITCH];
	uint8_t l0[BD3_L0_C * BD3_L0_H * BD3_L0_W];
	uint32_t p1[BD3_L0_C * BD3_P1_H * BD3_P1_W];	/* L1 */
	uint8_t l2[BD3_L2_C * BD3_L2_H * BD3_L2_W];
	uint32_t pa[BD3_TRUNK_C * BD3_P3_PLANE];	/* L3, L5, L7 */
	uint32_t pb[BD3_TRUNK_C * BD3_P3_PLANE];	/* L4, L6 */
	uint8_t l8[BD3_TRUNK_C * BD3_CELLS];
	uint32_t row[BD3_L2_W / 4];			/* one u8 row */
	int32_t logit[BD3_CELLS];	/* row-major [9][12] */
} __attribute__((aligned(64)));

/* end: the stage's last band. */
typedef void bd3_pause_fn(void *ctx, enum bd3_stage st, bool end);

/* Clears all buffers (the zero borders). */
void bd3_net_init(struct bd3_net *n);
/* Copies a 96x72 YUYV frame (word aligned, pitch BD3_FRAME_PITCH) into the input. */
void bd3_net_input(struct bd3_net *n, const uint8_t *frame);
/* The input of a test pattern. */
void bd3_net_pattern(struct bd3_net *n, enum bd3_pattern p);
/* Runs L0..L9 on n->in; pause (if not NULL) after each band: a stem row, an output row of a block
   of a ternary layer, a whole pool or the head (at most ~0.2 M cycles apart). */
void bd3_net_run(struct bd3_net *n, bd3_pause_fn *pause, void *ctx);
/* Rotate-add checksum of the logits in raster order. */
uint32_t bd3_logit_sum(const int32_t *logit);

#endif
