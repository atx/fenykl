/*
 * The bird detector network (fenykl-nn f1_pool96big_d105, docs/intspec.md there) in plain integer C.
 * Pure code, no firmware calls: runs on CPU1 and in the GDB simulator (tests/sim/birddetect).
 *
 * Layout: every tensor is channel-major (CHW) u8; a tensor that a 3x3 conv reads has a zero border of
 * one pixel around each channel plane, written once by bd_net_init and never again, so no kernel
 * needs bounds checks. A ternary layer reads its input as pair words (pixel p in the low 16 bits,
 * pixel p + 1 in the high 16 bits), so one load and one add or subtract per non-zero weight serve
 * two neighbouring outputs; its weights are lists of byte offsets into those words.
 */
#ifndef BD_NET_H
#define BD_NET_H

#include <stdint.h>

#define BD_SRC_W 640u			/* the FD frame, Y8 */
#define BD_SRC_H 480u
#define BD_IN_W 96u
#define BD_IN_H 72u
#define BD_GRID_W 12u
#define BD_GRID_H 9u
#define BD_CELLS (BD_GRID_W * BD_GRID_H)
#define BD_THRESHOLD (-18398)	/* model.json threshold.int32: a cell is a detection if >= */

/* Padded plane sizes (W + 2) x (H + 2); gen_weights.py bakes the same into the offsets. */
#define BD_PIN_W (BD_IN_W + 2)		/* input, 98 x 74 */
#define BD_PIN_H (BD_IN_H + 2)
#define BD_L0_C 12u			/* stem output, unpadded 12 x 36 x 48 */
#define BD_L0_W 48u
#define BD_L0_H 36u
#define BD_P1_W (BD_L0_W / 2 + 2)	/* L1 pool output, padded 12 x 20 x 26 */
#define BD_P1_H (BD_L0_H / 2 + 2)
#define BD_L2_C 16u			/* L2 output, unpadded 16 x 18 x 24 */
#define BD_L2_W 24u
#define BD_L2_H 18u
#define BD_P3_W (BD_GRID_W + 2)		/* L3 pool and L4-L8 outputs, padded 11 x 14 */
#define BD_P3_H (BD_GRID_H + 2)
#define BD_P3_PLANE (BD_P3_W * BD_P3_H)
#define BD_TRUNK_C 32u
#define BD_TRUNK_LAYERS 5u		/* L4..L8 */

/* A ternary 3x3 conv layer (gen_weights.py). */
struct bd_tern {
	uint16_t cout;
	const uint16_t *npos, *nneg;	/* per output channel: number of +1 and -1 offsets */
	const uint16_t *off;		/* per output channel: npos, then nneg byte offsets (4 per pixel) */
	const int32_t *bias;		/* bias + rounding term 1 << (shift - 1) */
	const uint8_t *shift;
};

/* bd_model.c, generated by gen_weights.py. */
extern const char bd_model_name[], bd_model_commit[];
extern const int8_t bd_l0_w[BD_L0_C][9];
extern const int32_t bd_l0_b[BD_L0_C];		/* bias + rounding */
extern const uint8_t bd_l0_s[BD_L0_C];
extern const struct bd_tern bd_l2, bd_trunk[BD_TRUNK_LAYERS];
extern const int8_t bd_l9_w[BD_TRUNK_C];
extern const int32_t bd_l9_b;
extern const uint32_t bd_selftest_sum[3];	/* bd_logit_sum of BD_PAT_* below */

struct bd_net {
	uint8_t in[BD_PIN_H * BD_PIN_W];
	uint8_t l0[BD_L0_C * BD_L0_H * BD_L0_W];
	uint8_t l1[BD_L0_C * BD_P1_H * BD_P1_W];
	uint8_t l2[BD_L2_C * BD_L2_H * BD_L2_W];
	uint8_t l3[BD_L2_C * BD_P3_PLANE];
	uint8_t trunk[BD_TRUNK_LAYERS][BD_TRUNK_C * BD_P3_PLANE];
	uint32_t pairs[BD_L0_C * BD_P1_H * BD_P1_W];	/* the ternary input, the largest is L2's */
	int32_t logit[BD_CELLS];	/* row-major [9][12] */
};

/* Stage groups for timing: the pause callback gets the group of the band just finished. */
enum bd_group {
	BD_G_STEM,	/* L0, L1 */
	BD_G_L2,	/* L2, L3 */
	BD_G_TRUNK,	/* L4..L9 */
	BD_GROUPS,
};

/* Input patterns of the fenykl-nn test vectors, for the self-test. */
enum bd_pattern {
	BD_PAT_HGRAD,
	BD_PAT_VGRAD,
	BD_PAT_CHECKER,
	BD_PATTERNS,
};

typedef void bd_pause_fn(void *ctx, enum bd_group g);

/* Clears all buffers (the zero borders). */
void bd_net_init(struct bd_net *n);
/* Pixel (x, y) of the 96 x 72 input. */
static inline uint8_t *bd_net_px(struct bd_net *n, unsigned int x, unsigned int y)
{
	return &n->in[(y + 1) * BD_PIN_W + x + 1];
}
/* Runs every layer on n->in; calls pause (if not NULL) after each band of rows, at most a few
   hundred thousand weight applications apart. */
void bd_net_run(struct bd_net *n, bd_pause_fn *pause, void *ctx);
/* Point-samples the 640x480 Y8 frame into the input (fenykl-nn handoff section 1). */
void bd_net_sample(struct bd_net *n, const uint8_t *frame);
/* Fills the input with a test pattern. */
void bd_net_pattern(struct bd_net *n, enum bd_pattern p);
/* Rotate-add checksum of the logits in raster order. */
uint32_t bd_logit_sum(const int32_t *logit);

#endif
