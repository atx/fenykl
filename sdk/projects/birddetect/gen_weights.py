"""Generate bd_model.c (weights in the layout of net.h) and the simulator test vectors from a shipped
fenykl-nn model directory (model.npz, model.json, testvectors.npz). Needs NumPy; run with any
python3 that has it:

    python3 gen_weights.py ../../../../fenykl-nn/models/f1_pool96big_d105 <fenykl-nn commit>
"""

import argparse
import base64
import json
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
VECTORS = HERE.parents[2] / "tests" / "sim" / "birddetect" / "vectors.json"
# Padded input planes (width, height) of the ternary layers, as BD_P1_* and BD_P3_* in net.h.
PADDED = {"L2": (26, 20), "L4": (14, 11), "L5": (14, 11), "L6": (14, 11), "L7": (14, 11), "L8": (14, 11)}
TRUNK = ["L4", "L5", "L6", "L7", "L8"]
# Test vectors in the simulator test; the structured ones are regenerated there.
NOISE = ["noise0", "noise1", "noise2"]
STRUCTURED = ["zero", "full", "hgradient", "vgradient", "checker"]
SELFTEST = ["hgradient", "vgradient", "checker"]  # enum bd_pattern order


def mix_sum(values) -> int:
    """Rotate-add checksum of 32-bit values (bd_logit_sum, the C test's layer sums)."""
    s = 0
    for v in values:
        s = (((s << 1) | (s >> 31)) + (int(v) & 0xFFFFFFFF)) & 0xFFFFFFFF
    return s


def rounded_bias(arrays, name) -> list[int]:
    shift = arrays[name + ".shift"].astype(np.int64)
    rnd = np.where(shift > 0, np.left_shift(1, np.maximum(shift - 1, 0)), 0)
    return [int(v) for v in arrays[name + ".b"].astype(np.int64) + rnd]


def c_array(ctype: str, name: str, values, per_line: int = 12) -> str:
    vals = [str(int(v)) for v in values]
    lines = [", ".join(vals[i : i + per_line]) for i in range(0, len(vals), per_line)]
    body = ",\n\t".join(lines)
    return f"static const {ctype} {name}[{len(vals)}] = {{\n\t{body},\n}};\n"


def ternary(arrays, name: str) -> tuple[str, int]:
    """Offset lists of one ternary layer: per output channel the +1 offsets, then the -1 offsets, in
    bytes into the pair words of net.c (4 per input pixel)."""
    w = arrays[name + ".w"]
    pw, ph = PADDED[name]
    assert set(np.unique(w)) <= {-1, 0, 1}, name
    # Each 16-bit lane holds 0x8000 + acc; intspec's acc_bound (incl. bias and rounding) must fit.
    bias = np.array(rounded_bias(arrays, name))
    bound = np.abs(w.astype(np.int64)).reshape(w.shape[0], -1).sum(axis=1) * 255 + np.abs(bias)
    assert bound.max() < 1 << 15, (name, bound.max())
    npos, nneg, off = [], [], []
    for o in range(w.shape[0]):
        for sign, counts in ((1, npos), (-1, nneg)):
            i, ky, kx = np.nonzero(w[o] == sign)
            off += list(4 * (i * pw * ph + ky * pw + kx))
            counts.append(len(i))
    assert max(off) < 1 << 16
    low = name.lower()
    src = (
        c_array("uint16_t", f"bd_{low}_np", npos)
        + c_array("uint16_t", f"bd_{low}_nn", nneg)
        + c_array("uint16_t", f"bd_{low}_off", off)
        + c_array("int32_t", f"bd_{low}_b", rounded_bias(arrays, name), 6)
        + c_array("uint8_t", f"bd_{low}_s", arrays[name + ".shift"])
    )
    return src, len(off)


def tern_init(name: str) -> str:
    low = name.lower()
    return (
        f"{{ .cout = sizeof(bd_{low}_np) / 2, .npos = bd_{low}_np, .nneg = bd_{low}_nn, "
        f".off = bd_{low}_off, .bias = bd_{low}_b, .shift = bd_{low}_s }}"
    )


def write_model(model_dir: Path, commit: str, arrays, desc, tv) -> None:
    assert desc["threshold"]["int32"] == -18398, "BD_THRESHOLD in net.h"
    l0w = arrays["L0.w"]
    assert l0w.shape == (12, 1, 3, 3)
    l9w = arrays["L9.w"]
    assert l9w.shape == (1, 32, 1, 1)
    kinds = list(tv["kind"])
    sums = [mix_sum(tv["L9"][kinds.index(k)].reshape(-1)) for k in SELFTEST]
    out = [
        f"/* Generated by gen_weights.py from fenykl-nn {model_dir.name} (commit {commit}).\n"
        "   Do not edit. Layout: net.h.\n"
        "   Trained by the separate fenykl-nn project on the bird class of the Open Images Dataset V7\n"
        "   (annotations CC BY 4.0, Google LLC; images listed as CC BY 2.0). No images are included here. */\n",
        '#include "net.h"\n\n',
        f'const char bd_model_name[] = "{model_dir.name}";\n',
        f'const char bd_model_commit[] = "{commit[:12]}";\n\n',
        "const int8_t bd_l0_w[BD_L0_C][9] = {\n"
        + "".join("\t{ " + ", ".join(str(int(v)) for v in l0w[o].reshape(-1)) + " },\n" for o in range(12))
        + "};\n",
        "const int32_t bd_l0_b[BD_L0_C] = { " + ", ".join(map(str, rounded_bias(arrays, "L0"))) + " };\n",
        "const uint8_t bd_l0_s[BD_L0_C] = { " + ", ".join(str(int(v)) for v in arrays["L0.shift"]) + " };\n\n",
    ]
    total = 0
    for name in ["L2", *TRUNK]:
        src, n = ternary(arrays, name)
        out.append(f"/* {name}: {n} non-zero weights */\n{src}\n")
        total += n
    out += [
        f"const struct bd_tern bd_l2 = {tern_init('L2')};\n",
        "const struct bd_tern bd_trunk[BD_TRUNK_LAYERS] = {\n"
        + "".join(f"\t{tern_init(n)},\n" for n in TRUNK)
        + "};\n\n",
        "const int8_t bd_l9_w[BD_TRUNK_C] = { " + ", ".join(str(int(v)) for v in l9w.reshape(-1)) + " };\n",
        f"const int32_t bd_l9_b = {int(arrays['L9.b'][0])};\n\n",
        "/* hgradient, vgradient, checker */\n",
        "const uint32_t bd_selftest_sum[3] = { " + ", ".join(f"0x{s:08x}u" for s in sums) + " };\n",
    ]
    (HERE / "bd_model.c").write_text("".join(out))
    print(f"bd_model.c: {total} ternary non-zero weights, self-test sums {[hex(s) for s in sums]}")


def write_vectors(model_dir: Path, commit: str, tv) -> None:
    """Per vector: every layer's rotate-add checksum (unpadded CHW bytes, head int32) and the head."""
    kinds = list(tv["kind"])
    layers = [f"L{i}" for i in range(10)]
    vectors = []
    for kind in NOISE + STRUCTURED:
        i = kinds.index(kind)
        v = {
            "kind": kind,
            "sums": [mix_sum(tv[n][i].reshape(-1)) for n in layers],
            "head": [int(x) for x in tv["L9"][i].reshape(-1)],
        }
        if kind in NOISE:
            v["input"] = base64.b64encode(tv["input"][i].tobytes()).decode()
        vectors.append(v)
    doc = {"model": model_dir.name, "commit": commit, "layers": layers, "vectors": vectors}
    VECTORS.parent.mkdir(parents=True, exist_ok=True)
    VECTORS.write_text(json.dumps(doc, indent=1) + "\n")
    print(f"{VECTORS}: {len(vectors)} vectors")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("model_dir", type=Path)
    ap.add_argument("commit", help="fenykl-nn commit the model comes from")
    args = ap.parse_args()
    with np.load(args.model_dir / "model.npz") as z:
        arrays = {k: z[k] for k in z.files}
    desc = json.loads((args.model_dir / "model.json").read_text())
    with np.load(args.model_dir / "testvectors.npz") as z:
        tv = {k: z[k] for k in z.files}
    write_model(args.model_dir, args.commit, arrays, desc, tv)
    write_vectors(args.model_dir, args.commit, tv)


if __name__ == "__main__":
    main()
