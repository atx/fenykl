/* --- helpers --- */

static void sim_put(struct sim_file *f, const char *text, unsigned int len)
{
	for (unsigned int i = 0; i < len; i++)
		f->data[i] = text[i];
	f->size = len;
	f->exists = 1;
}

static void sim_dump(const char *tag)
{
	static const char head[] = "\n#### ", file[] = "\n-- ", none[] = "(none)";

	sim_write(head, sizeof(head) - 1);
	sim_write(tag, sim_strlen(tag));
	for (unsigned int i = 0; i < SIM_FILES - 1; i++) {
		sim_write(file, sizeof(file) - 1);
		sim_write(sim_names[i], sim_strlen(sim_names[i]));
		sim_write("\n", 1);
		if (sim.f[i].exists)
			sim_write(sim.f[i].data, sim.f[i].size);
		else
			sim_write(none, sizeof(none) - 1);
	}
}

/* A new boot: what crt0 clears, and .data as the loader loads it. */
static int sim_boot(void)
{
	const struct fenykl_cfg_opt *o;

	for (char *p = fenykl_bss_start; p < fenykl_bss_end; p++)
		*p = 0;
	fenykl_cfg_for_each(o)
		*o->value = o->def;
	return fenykl_cfg_init();
}

static struct fenykl_cfg_stats sim_stats(void)
{
	struct fenykl_cfg_stats s;

	fenykl_cfg_get_stats(&s);
	return s;
}

static bool sim_same(const struct sim_file *a, const struct sim_file *b)
{
	if (a->exists != b->exists || a->size != b->size)
		return false;
	for (uint32_t i = 0; i < a->size; i++)
		if (a->data[i] != b->data[i])
			return false;
	return true;
}

/* --- scenarios --- */

/* Fresh card: defaults, the first save goes to CF0 with seq 1. */
static void sim_check_fresh(void)
{
	struct fenykl_cfg_stats s;

	SIM_CHECK(0, sim_boot() == FENYKL_CFG_ENOFILE);
	SIM_CHECK(0, sim_int == 10 && sim_enum == 1 && !fenykl_cfg_dirty());
	SIM_CHECK(0, fenykl_cfg_save() == 0 && sim.opens_w == 0);
	SIM_CHECK(1, fenykl_cfg_set(&fenykl_cfg_sim_int, 101) == FENYKL_CFG_EINVAL);
	SIM_CHECK(1, fenykl_cfg_set(&fenykl_cfg_sim_int, 15) == 0 && fenykl_cfg_dirty());
	SIM_CHECK(1, fenykl_cfg_save() == 0 && !fenykl_cfg_dirty());
	s = sim_stats();
	SIM_CHECK(1, s.slot == 0 && s.seq == 1 && s.saves == 1 && s.last_remove == -1);
	SIM_CHECK(1, mock_purges > 0);
	sim_dump("fresh");
}

/* Load, change, save into the other slot; the newer slot wins at the next boot. */
static void sim_check_alternate(void)
{
	struct fenykl_cfg_stats s;

	SIM_CHECK(2, sim_boot() == 0 && sim_int == 15);
	SIM_CHECK(2, fenykl_cfg_set(&fenykl_cfg_sim_bool, 1) == 0);
	SIM_CHECK(2, sim_changes == 1 && sim_last_old == 0);
	SIM_CHECK(2, fenykl_cfg_set(&fenykl_cfg_sim_bool, 1) == 0 && sim_changes == 1);
	SIM_CHECK(2, fenykl_cfg_save() == 0);
	SIM_CHECK(3, sim_boot() == 0);
	s = sim_stats();
	SIM_CHECK(3, s.slot == 1 && s.seq == 2 && sim_bool == 1 && sim_int == 15);
	SIM_CHECK(3, s.slot_state[0] == FENYKL_CFG_SLOT_VALID && s.slot_seq[0] == 1);
	sim_dump("alternate");
}

/* Power lost while CF0 was written: the torn file is rejected and CF1 loads. */
static void sim_check_torn(void)
{
	struct fenykl_cfg_stats s;

	SIM_CHECK(4, fenykl_cfg_set(&fenykl_cfg_sim_enum, 2) == 0 && fenykl_cfg_save() == 0);
	SIM_CHECK(4, sim_stats().slot == 0 && sim_stats().seq == 3);
	sim.f[SIM_CF0].size /= 2;
	SIM_CHECK(5, sim_boot() == 0);
	s = sim_stats();
	SIM_CHECK(5, s.slot == 1 && s.seq == 2 && sim_enum == 1);
	SIM_CHECK(5, s.slot_state[0] == FENYKL_CFG_SLOT_BAD_CRC);
	sim_dump("torn");
}

/* A remove that leaves the file aborts the save; a short write fails it, the old slot stays. */
static void sim_check_write_failures(void)
{
	struct sim_file cf0 = sim.f[SIM_CF0];
	uint32_t opens_w = sim.opens_w;
	struct fenykl_cfg_stats s;

	sim.remove_ret = 5;
	sim.remove_keeps = true;
	SIM_CHECK(6, fenykl_cfg_set(&fenykl_cfg_sim_int, 20) == 0);
	SIM_CHECK(6, fenykl_cfg_save() == FENYKL_CFG_EIO && fenykl_cfg_dirty());
	SIM_CHECK(6, sim.opens_w == opens_w && sim_same(&sim.f[SIM_CF0], &cf0));
	s = sim_stats();
	SIM_CHECK(6, s.last_remove == 5 && s.save_fail == 1 && s.slot == 1);
	sim.remove_keeps = false;
	sim.short_write = 40;
	SIM_CHECK(7, fenykl_cfg_save() == FENYKL_CFG_EIO && fenykl_cfg_dirty());
	SIM_CHECK(7, sim_stats().slot == 1 && sim_stats().save_fail == 2);
	sim.short_write = 0;
	SIM_CHECK(7, sim_boot() == 0 && sim_stats().slot == 1 && sim_int == 15);
	/* rpc_fremove fails but the file is gone: the save goes on. */
	SIM_CHECK(8, fenykl_cfg_set(&fenykl_cfg_sim_int, 20) == 0 && fenykl_cfg_save() == 0);
	s = sim_stats();
	SIM_CHECK(8, s.slot == 0 && s.seq == 3 && s.last_remove == 5);
	sim.remove_ret = 0;
	sim_dump("failures");
}

/* Good, bad, out-of-range, duplicate and unknown lines; a valid CRC with a bad header. */
static void sim_check_parser(void)
{
	struct fenykl_cfg_stats s;

	sim_put(&sim.f[SIM_CF0], sim_parser0, sim_parser0_len);
	sim_put(&sim.f[SIM_CF1], sim_parser1, sim_parser1_len);
	SIM_CHECK(9, sim_boot() == 0);
	s = sim_stats();
	SIM_CHECK(9, s.slot == 0 && s.seq == 100);
	SIM_CHECK(9, s.slot_state[1] == FENYKL_CFG_SLOT_BAD_HEADER);
	SIM_CHECK(10, sim_bool == 1 && sim_int == 10 && sim_enum == 0 && sim_big == 1000);
	SIM_CHECK(10, s.applied == 4 && s.invalid == 2 && s.unknown == 1);
	SIM_CHECK(10, s.duplicates == 2 && s.malformed == 2 && !s.raw_overflow);
	SIM_CHECK(11, !fenykl_cfg_dirty() && fenykl_cfg_set(&fenykl_cfg_sim_bool, 0) == 0);
	SIM_CHECK(11, fenykl_cfg_save() == 0 && sim_stats().seq == 101);
	sim_dump("parser");
	/* Setting an option with a carried line replaces the line. */
	SIM_CHECK(12, fenykl_cfg_set(&fenykl_cfg_sim_int, sim_int) == 0 && fenykl_cfg_dirty());
	SIM_CHECK(12, fenykl_cfg_save() == 0);
	sim_dump("parser-set");
}

/* The import goes through the same parser, is saved and then deleted. */
static void sim_check_import(void)
{
	struct fenykl_cfg_stats s;

	sim_put(&sim.f[SIM_IMPORT], sim_import, sim_import_len);
	SIM_CHECK(13, sim_boot() == 0);
	s = sim_stats();
	SIM_CHECK(13, s.imported && s.import_pending && fenykl_cfg_dirty());
	SIM_CHECK(13, sim_enum == 0 && sim_big == 1000 && sim_int == 10);
	SIM_CHECK(13, s.unknown == 3 && s.invalid == 2 && s.applied == 4);
	SIM_CHECK(14, fenykl_cfg_save() == 0 && !sim.f[SIM_IMPORT].exists);
	SIM_CHECK(14, !sim_stats().import_pending);
	sim_dump("import");
}

/* Carried lines beyond FENYKL_CFG_RAW: nothing is dropped, saving is refused. */
static void sim_check_overflow(void)
{
	struct sim_file cf0 = sim.f[SIM_CF0], cf1 = sim.f[SIM_CF1];

	sim_put(&sim.f[SIM_IMPORT], sim_overflow, sim_overflow_len);
	SIM_CHECK(15, sim_boot() == 0 && sim_stats().raw_overflow);
	SIM_CHECK(15, fenykl_cfg_save() == FENYKL_CFG_ENOSPC);
	SIM_CHECK(15, sim_same(&sim.f[SIM_CF0], &cf0) && sim_same(&sim.f[SIM_CF1], &cf1));
	SIM_CHECK(15, sim.f[SIM_IMPORT].exists);
	sim.f[SIM_IMPORT].exists = 0;
}

/* Gate closed at init: defaults, held; at the first open gate the file loads, set values win. */
static void sim_check_gate(void)
{
	struct fenykl_cfg_stats s;
	int32_t stored_enum = 0;

	SIM_CHECK(16, sim_boot() == 0);
	stored_enum = sim_enum;
	SIM_FAT_MOUNTED = 0;
	SIM_CHECK(16, sim_boot() == FENYKL_CFG_ENOCARD && sim_enum == 1);
	SIM_CHECK(16, fenykl_cfg_set(&fenykl_cfg_sim_big, 7) == 0);
	SIM_CHECK(16, fenykl_cfg_save() == FENYKL_CFG_ENOCARD && sim_stats().gate_holds == 1);
	SIM_FAT_MOUNTED = 1;
	SIM_CHECK(17, fenykl_cfg_save() == 0);
	s = sim_stats();
	SIM_CHECK(17, sim_big == 7 && sim_enum == stored_enum && s.saves == 1);
	sim_dump("gate");
}

/* A cable closes the gate until power-off: pulling it does not let the held save through. */
static void sim_check_cable(void)
{
	struct sim_file cf0, cf1;

	SIM_CHECK(20, sim_boot() == 0);
	cf0 = sim.f[SIM_CF0];
	cf1 = sim.f[SIM_CF1];
	mock_usb_key = 0;
	SIM_CHECK(20, fenykl_cfg_set(&fenykl_cfg_sim_big, 9) == 0);
	SIM_CHECK(20, fenykl_cfg_save() == FENYKL_CFG_ENOCARD);
	mock_usb_key = 1;
	SIM_CHECK(20, fenykl_cfg_save() == FENYKL_CFG_ENOCARD && fenykl_card_usb_seen());
	SIM_CHECK(20, fenykl_cfg_save() == FENYKL_CFG_ENOCARD && fenykl_cfg_dirty());
	SIM_CHECK(20, sim_stats().gate_holds == 1 && sim_stats().saves == 0);
	SIM_CHECK(20, sim_same(&sim.f[SIM_CF0], &cf0) && sim_same(&sim.f[SIM_CF1], &cf1));
}

static void sim_check_cpu1(void)
{
	SIM_CORE = 1;
	SIM_CHECK(18, fenykl_cfg_set(&fenykl_cfg_sim_int, 20) == FENYKL_CFG_ECONTEXT);
	SIM_CORE = 0;
}

/* Sequence numbers compare wrap-safe: seq 0 is newer than 0xFFFFFFFF. */
static void sim_check_wrap(void)
{
	sim_put(&sim.f[SIM_CF0], sim_wrap0, sim_wrap0_len);
	sim_put(&sim.f[SIM_CF1], sim_wrap1, sim_wrap1_len);
	SIM_CHECK(19, sim_boot() == 0 && sim_stats().slot == 1 && sim_stats().seq == 0);
	SIM_CHECK(19, sim_int == 25);
}

void plugin_main(uint32_t load_base, uint32_t image_size)
{
	(void)load_base;
	(void)image_size;
	SIM_FAT_MOUNTED = 1;
	sim_check_fresh();
	sim_check_alternate();
	sim_check_torn();
	sim_check_write_failures();
	sim_check_parser();
	sim_check_import();
	sim_check_overflow();
	sim_check_gate();
	sim_check_cable();
	sim_check_cpu1();
	sim_check_wrap();
	sim_write("\n", 1);
	sim_exit_code = sim.fail ? 1 + __builtin_ctz(sim.fail) : 0;
}
